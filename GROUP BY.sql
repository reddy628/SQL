CREATE DATABASE GROUPBY;
USE GROUPBY;
CREATE TABLE EMPLOYEE (
    EMP_ID INT,
    EMP_NAME VARCHAR(50),
    CITY VARCHAR(50),
    SALARY INT
);
INSERT INTO EMPLOYEE

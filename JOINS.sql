# INNER JOINS
SELECT
    E.EMP_ID,
    E.EMP_NAME,
    E.SALARY,
    D.DEPT_NAME
FROM EMPLOYEE E
INNER JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID;
# LEFT JOINS
SELECT
    E.EMP_ID,
    E.EMP_NAME,
    E.SALARY,
    D.DEPT_NAME
FROM EMPLOYEE E
LEFT JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID;
# RIGHT JOINS
SELECT
    E.EMP_ID,
    E.EMP_NAME,
    D.DEPT_ID,
    D.DEPT_NAME
FROM EMPLOYEE E
RIGHT JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID;
# FULL JOINS
SELECT
    E.EMP_ID,
    E.EMP_NAME,
    D.DEPT_NAME
FROM EMPLOYEE E
LEFT JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID

UNION

SELECT
    E.EMP_ID,
    E.EMP_NAME,
    D.DEPT_NAME
FROM EMPLOYEE E
RIGHT JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID;
# CROSS JOINS
SELECT
    E.EMP_NAME,
    D.DEPT_NAME
FROM EMPLOYEE E
CROSS JOIN DEPARTMENT D;
